def kind_of(item):
    for k, v in KIND.items():
        if k in item:
            return v
    return "기타"


def main():
    if os.path.exists(OUT_DIR):
        sys.exit("이미 있다 — 판을 덮어쓰지 않는다: " + OUT_DIR)
    old = list(csv.DictReader(io.open(SRC, encoding="utf-8-sig")))
    cols = list(old[0].keys()) + ["area"]
    out = []
    for i, (d, a, item, amt, note) in enumerate(PLAN, 1):
        planned = int(amt * 억)
        ratio = 0.35 + ((i * 37) % 46) / 100          # 0.35~0.80 고정
        use = USE[(a, item)]
        out.append({"budget_id": "BUD-%04d" % (100 + i), "fiscal_year": "2026", "dept_id": d, "target_code": "",
                    "budget_kind": kind_of(item), "budget_item": item, "budget_use": use,
                    "use_basis": BASIS[a] + ("" if use == "밖" else use + "목"),
                    "planned_amount": str(planned), "executed_amount": str(int(round(planned * ratio, -5))),
                    "risk_item_id": "", "duty_key": "", "updated_at": "2026-09-24", "note": "예시 자료(시연용) · " + note, "area": a})
    for r in old:
        if r["budget_id"] in KEEP:
            out.append({**r, "area": "I"})
    os.makedirs(OUT_DIR)
    with io.open(os.path.join(OUT_DIR, "safety_budget.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(out)
    tot = {}
    for r in out:
        tot[r["area"]] = tot.get(r["area"], 0) + int(r["planned_amount"])
    print("예산 %d줄 · " % len(out) + " · ".join("%s %.1f억" % (k, v / 억) for k, v in sorted(tot.items())),
          "· 예전 합계 %.0f억" % (sum(int(r["planned_amount"]) for r in old) / 억))


if __name__ == "__main__":
    main()
