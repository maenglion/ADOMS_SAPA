/**
 * 재해유형(사고 발생 형태) — 한 벌(09-26 사용자: 「재해유형 목록이 두 벌이다 → 하나로 맞추자」).
 *
 * 전: 세 벌이 따로 있었다 — 재발방지(「추락·낙하물·비래…」) · 유해·위험요인 신고(「떨어짐·맞음·깔림…」) · 발생통계 원장(「떨어짐·물체에 맞음…」).
 * 지금: 발생통계 원장의 이름(고용노동부 산업재해 발생 형태와 같은 말)을 기준으로 한 목록 하나.
 *   원장에 없는 형태(감전·화재·산소결핍 등)와 중대시민재해 쪽 형태(시설물 파손·행사 등의 사고)는 뒤에 붙였다.
 *   코드 관리(lib/codes.ts ACC_TYPE)의 기본값도 이 목록이다 — 화면은 codeValues("ACC_TYPE")로 받는다.
 *
 * 이미 저장된 옛 값은 고치지 않는다(데이터 판 · 기록). 읽을 때 accType()으로 새 이름에 맞춰 보여 주고 센다.
 * ★ 이 파일은 브라우저 쪽에서도 읽을 수 있게 파일·DB 를 읽지 않는다.
 */
export const ACC_TYPES = [
  "떨어짐", "넘어짐", "깔림·뒤집힘", "부딪힘", "물체에 맞음", "무너짐", "끼임", "절단·베임·찔림",
  "감전", "폭발·파열", "화재", "무리한 동작", "이상온도 접촉", "화학물질 누출", "산소결핍", "빠짐·익사",
  "교통사고(업무중)", "교통사고(업무 외)", "직업성 질병", "시설물 파손", "행사 등의 사고", "기타",
];

/** 옛 이름 → 새 이름(괄호 꼬리 「(위험)」 등은 떼어 맞춘 뒤 다시 붙인다). */
const OLD: Record<string, string> = {
  "추락": "떨어짐", "낙하물": "물체에 맞음", "비래": "물체에 맞음", "맞음": "물체에 맞음", "맞음(낙하·비래)": "물체에 맞음",
  "깔림": "깔림·뒤집힘", "붕괴·무너짐": "무너짐", "질식": "산소결핍", "근골격계": "무리한 동작",
  "중독·직업성 질병": "직업성 질병", "이상온도·물체접촉": "이상온도 접촉", "화학물질 누출·접촉": "화학물질 누출",
  "기관 내 교통사고": "교통사고(업무중)", "기관 외 교통사고": "교통사고(업무 외)",
};

export function accType(v?: string): string {
  const s = String(v || "").trim();
  if (!s || ACC_TYPES.includes(s)) return s;
  if (OLD[s]) return OLD[s];
  const m = s.match(/^(.*?)\s*(\(.*\))$/);          // 「추락(위험)」 → 「떨어짐(위험)」 · 「비래(튀는 물체)」 → 「물체에 맞음」
  if (m) {
    const head = OLD[m[1]] || m[1];
    if (m[1] === "비래") return head;
    return ACC_TYPES.includes(head) || OLD[m[1]] ? `${head}${m[2]}` : s;
  }
  return s;
}
