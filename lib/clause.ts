/** 참고 명세의 3단 등급 — 우수 80% 이상 · 보통 70% 이상 · 미흡 70% 미만 */
export const grade3 = (p: number, n: number) => (!n ? "none" : p >= 80 ? "ok" : p >= 70 ? "warn" : "bad");

/** 과제 한 건의 기호 — 점검 결과가 있으면 그것, 없으면 이행 상태(이행 현황표와 같은 규칙). N = 해당없음 */
export const markOf = (r: any): "O" | "T" | "X" | "N" => {
  if (r.applicability === "비해당") return "N";
  const c = r.check_result;
  if (c === "이행완료") return "O";
  if (c === "보완필요") return "T";
  if (c === "미이행") return "X";
  if (r.status === "이행완료" || r.status === "점검완료") return "O";
  if (r.status === "조치필요") return "T";
  return "X";
};
